# 課題9：フィボナッチ数列の計算
# - フィボナッチ数列を計算する関数を定義する（関数名・引数名は任意）
# - ルール
#   - 1番目 = 1
#   - 2番目 = 1
#   - 3番目以降 = 直前2つの和
#     - 例:
#       - 3番目: 1 + 1 = 2
#       - 4番目: 1 + 2 = 3
#       - 5番目: 2 + 3 = 5
#       - 6番目: 3 + 5 = 8
# - 再帰関数で実装する
# - 無限ループにならないよう終了条件を設定する

def fibonacci(n):
    if n <= 0:
        return 0
    elif n == 1 or n == 2:
        return 1
    else:
        return fibonacci(n - 1) + fibonacci(n - 2)